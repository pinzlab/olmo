import { DecodeError, type Field } from '../base'

type Enum = Record<string, string | number>

/**
 * Creates a field capable of decoding values from a TypeScript enumeration.
 *
 * The enumeration object is used to determine the set of permitted values.
 * Both string and numeric enums are supported.
 *
 * For numeric enums, string representations of numeric values are converted
 * to numbers before validation. TypeScript's reverse mappings for numeric
 * enums are ignored.
 *
 * The zero value is always the empty string (`""`), independently of the
 * values defined by the enumeration.
 *
 * The empty string, `null`, and `undefined` are treated as the field's
 * empty/initial representation and are decoded to the zero value.
 *
 * @param enumObject The TypeScript enumeration containing the permitted values.
 * @returns A Field capable of safely decoding values from the enumeration.
 *
 * @throws {Error} If the enumeration does not contain any values.
 * @throws {DecodeError} If the input cannot be decoded into a permitted
 * enumeration value.
 *
 * @example
 * String enumeration:
 *
 * ```ts
 * enum Role {
 *   Admin = 'admin',
 *   User = 'user',
 * }
 *
 * const role = enumeration(Role)
 *
 * role.zero() // ""
 * role.decode('') // ""
 * role.decode('admin') // Role.Admin
 * role.decode('user') // Role.User
 * ```
 */
export function enumeration<E extends Enum>(enumObject: E): Field<E[keyof E]> {
  const values = Object.values(enumObject).filter((value): value is E[keyof E] => {
    // Remove reverse mappings generated by numeric enums.
    if (typeof value === 'string') {
      return !Object.values(enumObject).some(
        numericValue =>
          typeof numericValue === 'number' && enumObject[numericValue] === value
      )
    }

    return true
  })

  if (values.length === 0) {
    throw new Error('Enumeration must have at least one permitted value')
  }

  return {
    zero(): E[keyof E] {
      return '' as E[keyof E]
    },

    decode(input: unknown): E[keyof E] {
      if (input === null || input === undefined || input === '') {
        return '' as E[keyof E]
      }

      let testValue: unknown = input

      const firstValue = values[0]

      if (typeof firstValue === 'number' && typeof input === 'string') {
        const parsed = Number(input)

        if (!Number.isNaN(parsed)) {
          testValue = parsed
        }
      }

      if (values.includes(testValue as E[keyof E])) {
        return testValue as E[keyof E]
      }

      throw new DecodeError('Cannot decode input into any permitted enumeration value')
    }
  }
}
